//! The build system, also written in Rust, because of course it is.
//!
//!   cargo xtask dist          build dist/htmx-rs.js (wasm inlined, one file, CDN-ready)
//!   cargo xtask site          build target/site (demo + bundle) for GitHub Pages
//!   cargo xtask serve [port]  build the site and serve it locally (default 8080)

use std::error::Error;
use std::fs;
use std::io::{Read, Write};
use std::net::{TcpListener, TcpStream};
use std::path::{Path, PathBuf};
use std::process::Command;

type R<T = ()> = Result<T, Box<dyn Error>>;

const VERSION: &str = env!("CARGO_PKG_VERSION");
/// htmx's own claim for its minified + gzipped size, for the benchmarks table.
const HTMX_MIN_GZ: &str = "~14 KB";

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let result = match args.first().map(String::as_str) {
        Some("dist") => dist().map(|_| ()),
        Some("site") => dist().and_then(site),
        Some("serve") => {
            let port = args.get(1).and_then(|p| p.parse().ok()).unwrap_or(8080);
            dist().and_then(site).and_then(|_| serve(port))
        }
        _ => {
            eprintln!("usage: cargo xtask <dist | site | serve [port]>");
            std::process::exit(2);
        }
    };
    if let Err(e) = result {
        eprintln!("xtask: {e}");
        std::process::exit(1);
    }
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_path_buf()
}

struct Sizes {
    raw: usize,
    gz: usize,
}

fn dist() -> R<Sizes> {
    let root = root();
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());

    println!("🦀 compiling htmx-rs to wasm32 (this is the build step htmx doesn't have)");
    let status = Command::new(cargo)
        .current_dir(&root)
        .args([
            "build",
            "-p",
            "htmx-rs",
            "--release",
            "--target",
            "wasm32-unknown-unknown",
        ])
        .status()?;
    if !status.success() {
        return Err(
            "wasm build failed. Did you run `rustup target add wasm32-unknown-unknown`?".into(),
        );
    }

    println!("🦀 generating the JavaScript we don't talk about");
    let wasm = root.join("target/wasm32-unknown-unknown/release/htmx_rs.wasm");
    let out = root.join("target/bindgen");
    fs::create_dir_all(&out)?;
    wasm_bindgen_cli_support::Bindgen::new()
        .input_path(&wasm)
        .no_modules(true)?
        .typescript(false)
        .generate(&out)?;
    let glue = fs::read_to_string(out.join("htmx_rs.js"))?;
    let bytes = fs::read(out.join("htmx_rs_bg.wasm"))?;

    let bundle = format!(
        r#"/*! htmx-rs v{VERSION} | 0BSD | htmx, rewritten in Rust 🦀
 * Generated by `cargo xtask dist`. The Rust is inlined below as WebAssembly.
 * The JavaScript around it is glue. We don't talk about the glue. */
(function () {{
"use strict";
{glue}
var b = atob("{b64}"), u = new Uint8Array(b.length);
for (var i = 0; i < b.length; i++) u[i] = b.charCodeAt(i);
wasm_bindgen({{ module_or_path: u }}).catch(function (e) {{
  console.error("htmx-rs: the crab failed to start", e);
}});
}})();
"#,
        b64 = base64(&bytes),
    );

    let dist = root.join("dist");
    fs::create_dir_all(&dist)?;
    fs::write(dist.join("htmx-rs.js"), &bundle)?;
    fs::write(dist.join("package.json"), package_json())?;
    for f in ["README.md", "LICENSE"] {
        fs::copy(root.join(f), dist.join(f))?;
    }

    let sizes = Sizes {
        raw: bundle.len(),
        gz: gzip_len(bundle.as_bytes())?,
    };
    println!(
        "🦀 dist/htmx-rs.js: {} raw, {} gzipped (htmx is {HTMX_MIN_GZ}; we are winning at being bigger)",
        kb(sizes.raw),
        kb(sizes.gz)
    );
    Ok(sizes)
}

fn site(sizes: Sizes) -> R {
    let root = root();
    let site = root.join("target/site");
    if site.exists() {
        fs::remove_dir_all(&site)?;
    }
    copy_dir(&root.join("examples/demo"), &site)?;
    fs::copy(root.join("dist/htmx-rs.js"), site.join("htmx-rs.js"))?;

    // Fill in the real numbers for the benchmarks table.
    let bench = site.join("fragments/benchmarks.html");
    let html = fs::read_to_string(&bench)?
        .replace("{{HTMX_SIZE}}", HTMX_MIN_GZ)
        .replace("{{RS_SIZE}}", &kb(sizes.gz))
        .replace("{{VERSION}}", VERSION);
    fs::write(bench, html)?;

    println!("🦀 site built in target/site");
    Ok(())
}

fn serve(port: u16) -> R {
    let site = root().join("target/site");
    let listener = TcpListener::bind(("127.0.0.1", port))?;
    println!("🦀 serving the demo at http://localhost:{port} (ctrl-c to stop)");
    for stream in listener.incoming().flatten() {
        let site = site.clone();
        std::thread::spawn(move || {
            let _ = handle(stream, &site);
        });
    }
    Ok(())
}

/// A static file server in ~30 lines. It answers POST/PUT/PATCH/DELETE with the file too,
/// so the demo's buttons work no matter the verb. Do not put this on the internet.
fn handle(mut stream: TcpStream, site: &Path) -> R {
    let mut buf = [0u8; 16 * 1024];
    let n = stream.read(&mut buf)?;
    let req = String::from_utf8_lossy(&buf[..n]);
    let path = req.split_whitespace().nth(1).unwrap_or("/");
    let path = path
        .split('?')
        .next()
        .unwrap_or("/")
        .trim_start_matches('/');
    let path = if path.is_empty() { "index.html" } else { path };
    let file = site.join(path);
    let (status, body, ty) = if path.contains("..") || !file.is_file() {
        (
            "404 Not Found",
            b"<p>404. Not even Rust can find this.</p>".to_vec(),
            "text/html",
        )
    } else {
        ("200 OK", fs::read(&file)?, content_type(&file))
    };
    write!(
        stream,
        "HTTP/1.1 {status}\r\nContent-Type: {ty}\r\nContent-Length: {}\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n",
        body.len()
    )?;
    stream.write_all(&body)?;
    Ok(())
}

fn content_type(p: &Path) -> &'static str {
    match p.extension().and_then(|e| e.to_str()) {
        Some("html") => "text/html; charset=utf-8",
        Some("js") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("svg") => "image/svg+xml",
        Some("json") => "application/json",
        Some("wasm") => "application/wasm",
        _ => "application/octet-stream",
    }
}

fn package_json() -> String {
    let repo = std::env::var("GITHUB_REPOSITORY")
        .map(|r| {
            format!(
                ",\n  \"repository\": {{ \"type\": \"git\", \"url\": \"https://github.com/{r}\" }}"
            )
        })
        .unwrap_or_default();
    format!(
        r#"{{
  "name": "htmx-rs",
  "version": "{VERSION}",
  "description": "htmx, rewritten in Rust. Blazingly fast. Memory safe. Slightly larger.",
  "main": "htmx-rs.js",
  "unpkg": "htmx-rs.js",
  "jsdelivr": "htmx-rs.js",
  "files": ["htmx-rs.js", "README.md", "LICENSE"],
  "license": "0BSD",
  "keywords": ["htmx", "rust", "wasm", "webassembly", "hypermedia", "blazingly-fast"]{repo}
}}
"#
    )
}

fn copy_dir(from: &Path, to: &Path) -> R {
    fs::create_dir_all(to)?;
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let dest = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_dir(&entry.path(), &dest)?;
        } else {
            fs::copy(entry.path(), dest)?;
        }
    }
    Ok(())
}

fn gzip_len(bytes: &[u8]) -> R<usize> {
    let mut gz = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
    gz.write_all(bytes)?;
    Ok(gz.finish()?.len())
}

fn kb(n: usize) -> String {
    format!("{:.1} KB", n as f64 / 1024.0)
}

/// Base64 without a crate, because every dependency is a supply-chain attack waiting to happen.
/// (Please ignore the dependency tree of wasm-bindgen-cli-support.)
fn base64(bytes: &[u8]) -> String {
    const A: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut s = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for c in bytes.chunks(3) {
        let n = (c[0] as u32) << 16
            | (*c.get(1).unwrap_or(&0) as u32) << 8
            | *c.get(2).unwrap_or(&0) as u32;
        s.push(A[(n >> 18) as usize & 63] as char);
        s.push(A[(n >> 12) as usize & 63] as char);
        s.push(if c.len() > 1 {
            A[(n >> 6) as usize & 63] as char
        } else {
            '='
        });
        s.push(if c.len() > 2 {
            A[n as usize & 63] as char
        } else {
            '='
        });
    }
    s
}

